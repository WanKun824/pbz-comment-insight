import re


def R(p: str):
    """编译 → bool 命中。"""
    return re.compile(p).search


def N(p: str):
    """编译 → 不同命中词个数（用于「净极性」计数）。"""
    r = re.compile(p)
    return lambda t: len(set(r.findall(t)))


